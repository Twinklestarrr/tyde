import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import prettier from 'prettier';

// The two committed design snapshots are the only generator inputs; regeneration
// does not depend on a developer's external documentation directory.
const directory = new URL('../packages/shared/src/agent/contracts/', import.meta.url);
const files = ['21-commands.openapi.json', '22-reads-events.openapi.json'];
const schemas = {};
const sources = [];
const operations = {};
const rename = (name) => (name === 'ErrorDetails' ? 'CommandErrorDetails' : name);
const referenceName = (reference) => rename(reference.split('/').at(-1));

function normalize(value) {
  if (Array.isArray(value)) return value.map(normalize);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, entry]) => [
      key,
      key === '$ref' ? `#/$defs/${referenceName(entry)}` : normalize(entry),
    ]),
  );
}

for (const file of files) {
  const bytes = await readFile(new URL(`sources/${file}`, directory));
  const document = JSON.parse(bytes.toString('utf8'));
  sources.push({
    file,
    designVersion: document.info.version,
    openapi: document.openapi,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  });
  for (const [path, item] of Object.entries(document.paths)) {
    if (path in operations) throw new Error(`Conflicting contract path: ${path}`);
    operations[path] = normalize(item);
  }
  for (const [originalName, value] of Object.entries(document.components.schemas)) {
    const name = rename(originalName);
    const normalized = normalize(value);
    if (name in schemas && JSON.stringify(schemas[name]) !== JSON.stringify(normalized)) {
      throw new Error(`Conflicting contract schema: ${name}`);
    }
    schemas[name] = normalized;
  }
}

const definitions = Object.fromEntries(
  Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b)),
);
const schemaId = 'urn:tyde:agent:public-contract:v1';
const contractDocument = { $id: schemaId, $defs: definitions };
const pending = new Set();
const ordered = [];
const done = new Set();

function references(value) {
  if (Array.isArray(value)) return value.flatMap(references);
  if (value === null || typeof value !== 'object') return [];
  return [
    ...(value.$ref ? [referenceName(value.$ref)] : []),
    ...Object.values(value).flatMap(references),
  ];
}

function visit(name) {
  if (done.has(name)) return;
  if (pending.has(name)) throw new Error(`Recursive schema is not supported: ${name}`);
  if (!definitions[name]) throw new Error(`Unknown schema reference: ${name}`);
  pending.add(name);
  for (const dependency of references(definitions[name])) visit(dependency);
  pending.delete(name);
  done.add(name);
  ordered.push(name);
}
for (const name of Object.keys(definitions)) visit(name);

function expression(schema) {
  if (schema.$ref) return `${referenceName(schema.$ref)}Schema`;
  return `/*#__PURE__*/ ${constructorExpression(schema)}`;
}

function constructorExpression(schema) {
  const metadata = Object.fromEntries(
    Object.entries(schema).filter(
      ([key]) =>
        !['type', 'properties', 'required', 'items', 'const', 'enum', 'oneOf', 'allOf'].includes(
          key,
        ),
    ),
  );
  const options = Object.keys(metadata).length ? `, ${JSON.stringify(metadata)}` : '';
  if (schema.oneOf) return `oneOf([${schema.oneOf.map(expression).join(', ')}]${options})`;
  if (schema.allOf) return `Type.Intersect([${schema.allOf.map(expression).join(', ')}]${options})`;
  if ('const' in schema) {
    return schema.const === null
      ? `Type.Null(${JSON.stringify(metadata)})`
      : `Type.Literal(${JSON.stringify(schema.const)}${options})`;
  }
  if (schema.enum)
    return `Type.Union([${schema.enum.map((value) => `/*#__PURE__*/ Type.Literal(${JSON.stringify(value)})`).join(', ')}]${options})`;
  if (schema.type === 'object' || schema.properties) {
    const required = new Set(schema.required ?? []);
    const properties = Object.entries(schema.properties ?? {}).map(([key, value]) => {
      const child = expression(value);
      return `${JSON.stringify(key)}: ${required.has(key) ? child : `/*#__PURE__*/ Type.Optional(${child})`}`;
    });
    return `Type.Object({${properties.join(', ')}}${options})`;
  }
  if (schema.type === 'array') return `Type.Array(${expression(schema.items)}${options})`;
  const constructor =
    { string: 'String', integer: 'Integer', number: 'Number', boolean: 'Boolean', null: 'Null' }[
      schema.type
    ] ?? 'Unknown';
  return `Type.${constructor}(${JSON.stringify(metadata)})`;
}

const banner = '// Generated by scripts/generate-agent-contracts.mjs. Do not edit by hand.\n';
const typebox = `${banner}
import { Type, type Static, type TSchema, type TUnion, type SchemaOptions } from '@sinclair/typebox';

// Retain exact JSON Schema oneOf semantics. TypeBox's anyOf additionally carries
// the static TypeScript union; validate with validateAgentContract, not Value.Check.
function oneOf<T extends TSchema[]>(variants: [...T], options: SchemaOptions = {}): TUnion<T> {
  return /*#__PURE__*/ Type.Union(variants, { ...options, oneOf: variants }) as TUnion<T>;
}

${ordered.map((name) => `export const ${name}Schema = ${expression(definitions[name])};\nexport type ${name} = Static<typeof ${name}Schema>;`).join('\n\n')}

export const agentContractSchemas = {${Object.keys(definitions)
  .map((name) => `${name}: ${name}Schema`)
  .join(', ')}} as const;
export type AgentContractName = keyof typeof agentContractSchemas;
export type AgentContractTypes = { [K in AgentContractName]: Static<(typeof agentContractSchemas)[K]> };
export const agentContractSources = ${JSON.stringify(sources)} as const;
`;

const ajv = new Ajv2020({
  strict: true,
  // The design deliberately refines closed objects via allOf properties without
  // restating type/required. Those refinements are valid JSON Schema.
  strictTypes: false,
  strictRequired: false,
  allErrors: false,
  inlineRefs: false,
  coerceTypes: false,
  removeAdditional: false,
  useDefaults: false,
  code: { esm: true, source: true, optimize: true },
});
for (const keyword of [
  'discriminator',
  'x-semantic-maximum',
  'x-sse-event-name',
  'x-sse-id-format',
]) {
  ajv.addKeyword({ keyword, valid: true });
}
// RegExp formats can be emitted by Ajv standalone without dynamic compilation or
// runtime imports. Calendar validity and offset bounds are checked in contracts/index.ts.
ajv.addFormat(
  'uuid',
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/,
);
ajv.addFormat('date', /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/);
ajv.addFormat(
  'date-time',
  /^[0-9]{4}-[0-9]{2}-[0-9]{2}[Tt][0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]+)?(?:[Zz]|[+-][0-9]{2}:[0-9]{2})$/,
);
ajv.addSchema(contractDocument);
const validators = Object.fromEntries(
  Object.keys(definitions).map((name) => [name, `${schemaId}#/$defs/${name}`]),
);
let standalone = standaloneCode(ajv, validators);
// Ajv emits its Unicode-length helper as a CommonJS runtime dependency. The
// equivalent code-point operation is tiny; inline our own helper so browser and
// Electron builds have no Ajv, require(), eval(), or new Function dependency.
standalone = standalone.replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  'agentUnicodeLength',
);
if (/\brequire\s*\(/.test(standalone) || /\bnew Function\b|\beval\s*\(/.test(standalone)) {
  throw new Error('Standalone validator unexpectedly needs a runtime dependency or dynamic code');
}
const standaloneModule = `${banner}/* eslint-disable */\n// @ts-nocheck -- Ajv standalone generated implementation; typed facade is index.ts.\nconst agentUnicodeLength = (value) => [...value].length;\n${standalone}`;

const output = {
  'generated.ts': typebox,
  'validator.generated.ts': standaloneModule,
  'document.generated.ts': `${banner}export const agentContractDocument = ${JSON.stringify(contractDocument)} as const;\n`,
  'operations.generated.ts': `${banner}export const agentContractOperations = ${JSON.stringify(operations)} as const;\n`,
};
const check = process.argv.includes('--check');
let mismatched = false;
for (const [file, source] of Object.entries(output)) {
  const url = new URL(file, directory);
  const formatted = await prettier.format(source, {
    ...(await prettier.resolveConfig(fileURLToPath(url))),
    filepath: fileURLToPath(url),
  });
  if (check) {
    const existing = await readFile(url, 'utf8').catch(() => '');
    if (existing !== formatted) {
      console.error(`Agent contract artifact is stale: ${file}`);
      mismatched = true;
    }
  } else {
    await writeFile(url, formatted);
  }
}
if (mismatched) process.exitCode = 1;
else
  console.log(
    `Agent contracts ${check ? 'verified' : 'generated'}: ${Object.keys(definitions).length} schemas from ${sources.length} design snapshots`,
  );
